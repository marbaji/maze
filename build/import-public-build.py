#!/usr/bin/env python3
"""Turn the public game build into build/input/game-public.html.

Usage: build/import-public-build.py <public-build.html>

Four anchored edits; each must match exactly the stated number of times or the
script exits non-zero and writes nothing.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "input" / "game-public.html"

FONTS_LINK = re.compile(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com/[^"]*">')
PROVENANCE = re.compile(r'<!-- Public read-only copy of [^\n]*? Do not edit this file: edit the original and rebuild\. -->\n?')
# The worker prelude is a double-quoted JS string, so the source text is importScripts('...') with plain quotes.
SES_CALL = "importScripts('https://cdn.jsdelivr.net/npm/ses@2.3.0/dist/ses.umd.min.js')"
PRELUDE_HEAD = 'const SES_PRELUDE = "var SES_STATE = '
# A blob worker resolves relative paths against the blob URL, so the page computes an absolute URL.
PRELUDE_HEAD_NEW = ('const SES_PRELUDE = "var SES_URL = " + JSON.stringify(typeof location === \'undefined\' ? \'\' : '
                    'new URL(\'vendor/ses.umd.min.js\', location.href).href) + "; var SES_STATE = ')


def replace_exact(text, old, new, count, label):
    found = len(old.findall(text)) if hasattr(old, "findall") else text.count(old)
    if found != count:
        sys.exit(f"FAILED: {label}: expected {count} match(es), found {found}")
    return old.sub(lambda _m: new, text) if hasattr(old, "sub") else text.replace(old, new)


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: import-public-build.py <public-build.html>")
    text = Path(sys.argv[1]).read_text(encoding="utf-8")
    text = replace_exact(text, PROVENANCE, "", 1, "provenance comment")
    text = replace_exact(text, FONTS_LINK, '<link rel="stylesheet" href="fonts/fonts.css">', 1, "Google Fonts link")
    text = replace_exact(text, PRELUDE_HEAD, PRELUDE_HEAD_NEW, 1, "SES_PRELUDE head")
    text = replace_exact(text, SES_CALL, "importScripts(SES_URL)", 1, "SES importScripts call")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"OK wrote {OUT} ({len(text)} chars)")


if __name__ == "__main__":
    main()
